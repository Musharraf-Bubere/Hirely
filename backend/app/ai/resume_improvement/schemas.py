from enum import Enum
from uuid import UUID

from pydantic import BaseModel, Field

from app.ai.ats_analyzer.schemas import ATSScoreBreakdown


class ActionPriority(str, Enum):
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class SectionStatus(str, Enum):
    STRONG = "strong"
    NEEDS_IMPROVEMENT = "needs_improvement"
    MISSING = "missing"


class ResumeImprovementRequest(BaseModel):
    job_id: UUID = Field(
        ...,
        description="ID of the target job to analyze the resume against.",
    )


class ImprovementAction(BaseModel):
    priority: ActionPriority = Field(
        description="Priority level: 'high', 'medium', or 'low'.",
    )
    category: str = Field(
        description="Area of improvement, e.g. 'Skills', 'Experience', 'Summary', 'Projects'.",
    )
    title: str = Field(
        description="Concise, actionable action title.",
    )
    recommendation: str = Field(
        description="Specific advice on what to adjust or highlight.",
    )
    rationale: str = Field(
        description="Explanation of why this change improves alignment with the target job.",
    )
    requires_candidate_verification: bool = Field(
        default=False,
        description="True if this recommendation requires the candidate to personally confirm they have this qualification or experience.",
    )


class SectionImprovement(BaseModel):
    section_name: str = Field(
        description="Name of the resume section, e.g. 'Summary', 'Experience', 'Projects', 'Skills', 'Education', 'Certifications'.",
    )
    current_status: SectionStatus = Field(
        description="Evaluated section status: 'strong', 'needs_improvement', or 'missing'.",
    )
    suggestions: list[str] = Field(
        default_factory=list,
        description="Actionable suggestions specific to this section.",
    )


class ResumeImprovementAIResult(BaseModel):
    """
    Structured model generated by Gemini.
    Numerical ATS scoring and deterministic skill matching are handled separately
    by the deterministic analyzer and merged in the final response.
    """

    overall_assessment: str = Field(
        description="High-level qualitative assessment of how the resume matches the target role.",
    )
    prioritized_actions: list[ImprovementAction] = Field(
        default_factory=list,
        description="Prioritized concrete improvement actions for the candidate.",
    )
    required_skill_recommendations: list[str] = Field(
        default_factory=list,
        description="Actionable recommendations addressing missing or weakly evidenced required skills.",
    )
    preferred_skill_recommendations: list[str] = Field(
        default_factory=list,
        description="Actionable recommendations addressing missing or weakly evidenced preferred skills.",
    )
    section_improvements: list[SectionImprovement] = Field(
        default_factory=list,
        description="Section-by-section breakdown with current status and targeted advice.",
    )
    summary_improvements: list[str] = Field(
        default_factory=list,
        description="Specific suggestions for the professional summary or headline.",
    )
    experience_improvements: list[str] = Field(
        default_factory=list,
        description="Specific suggestions for strengthening experience bullet points and relevance.",
    )
    project_improvements: list[str] = Field(
        default_factory=list,
        description="Specific suggestions for project descriptions and technical relevance.",
    )
    skills_improvements: list[str] = Field(
        default_factory=list,
        description="Specific suggestions for organizing skills and aligning industry terminology.",
    )


class ResumeImprovementResult(BaseModel):
    """
    Assembled candidate-facing result combining deterministic ATS metrics
    with Gemini qualitative improvement guidance.
    """

    overall_assessment: str
    ats_score: int = Field(
        ge=0,
        le=100,
        description="Deterministic ATS score calculated by Hirely's scoring engine.",
    )
    score_breakdown: ATSScoreBreakdown
    missing_required_skills: list[str] = Field(
        default_factory=list,
    )
    missing_preferred_skills: list[str] = Field(
        default_factory=list,
    )
    prioritized_actions: list[ImprovementAction] = Field(
        default_factory=list,
    )
    required_skill_recommendations: list[str] = Field(
        default_factory=list,
    )
    preferred_skill_recommendations: list[str] = Field(
        default_factory=list,
    )
    section_improvements: list[SectionImprovement] = Field(
        default_factory=list,
    )
    summary_improvements: list[str] = Field(
        default_factory=list,
    )
    experience_improvements: list[str] = Field(
        default_factory=list,
    )
    project_improvements: list[str] = Field(
        default_factory=list,
    )
    skills_improvements: list[str] = Field(
        default_factory=list,
    )


class ResumeImprovementResponse(BaseModel):
    job_id: UUID
    resume_improvement: ResumeImprovementResult
