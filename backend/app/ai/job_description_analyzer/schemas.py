from enum import Enum
from uuid import UUID

from pydantic import BaseModel, Field


class IssuePriority(str, Enum):
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class IssueCategory(str, Enum):
    CLARITY = "clarity"
    COMPLETENESS = "completeness"
    REQUIREMENTS = "requirements"
    SKILLS = "skills"
    TONE = "tone"
    STRUCTURE = "structure"


class JobDescriptionIssue(BaseModel):
    priority: IssuePriority = Field(
        description="Severity level of the issue: 'high', 'medium', or 'low'.",
    )
    category: IssueCategory = Field(
        description="Category of the issue: 'clarity', 'completeness', 'requirements', 'skills', 'tone', or 'structure'.",
    )
    title: str = Field(
        description="Short, descriptive headline for the issue.",
    )
    explanation: str = Field(
        description="Explanation of why this element is unclear, incomplete, or problematic.",
    )
    suggested_action: str = Field(
        description="Concrete, practical advice on how the recruiter can resolve this issue.",
    )


class JobSkillsAnalysis(BaseModel):
    required_skills_evaluation: str = Field(
        description="Assessment of whether required skills are realistic, specific, and clearly stated.",
    )
    preferred_skills_evaluation: str = Field(
        description="Assessment of preferred or nice-to-have skills and how well they are distinguished from mandatory ones.",
    )
    unmentioned_skills_in_description: list[str] = Field(
        default_factory=list,
        description="Skills associated with the job in the database that are not mentioned or contextualized in the description text.",
    )
    suggested_skills_to_add: list[str] = Field(
        default_factory=list,
        description="Relevant skills explicitly mentioned in the description text that could be tagged in the database.",
    )


class JobDescriptionAIResult(BaseModel):
    """
    Structured model generated by Gemini for Job Description Analysis.
    """

    quality_score: int = Field(
        ge=0,
        le=100,
        description="Heuristic job description quality score from 0 to 100 based on clarity, completeness, specificity, and realistic expectations.",
    )
    overall_assessment: str = Field(
        description="Concise high-level evaluation of the job description's effectiveness and readiness.",
    )
    strengths: list[str] = Field(
        default_factory=list,
        description="Positive aspects of the job description grounded in the provided text.",
    )
    issues: list[JobDescriptionIssue] = Field(
        default_factory=list,
        description="Prioritized list of clarity, completeness, requirements, or skills issues.",
    )
    missing_information: list[str] = Field(
        default_factory=list,
        description="Key information missing from the description (e.g. day-to-day duties, tech stack version, work arrangement details).",
    )
    skills_analysis: JobSkillsAnalysis = Field(
        description="Detailed review of how required and preferred skills are represented.",
    )
    improvement_recommendations: list[str] = Field(
        default_factory=list,
        description="Actionable, job-specific recommendations to improve candidate conversion and role clarity.",
    )
    improved_description: str | None = Field(
        default=None,
        description="Optional improved draft of the job description preserving verified source facts and using explicit placeholders for missing details.",
    )


class JobDescriptionAnalysisResult(BaseModel):
    """
    Assembled recruiter-facing analysis result combining Gemini output with heuristic disclaimers.
    """

    quality_score: int = Field(
        ge=0,
        le=100,
        description="Heuristic quality score from 0 to 100.",
    )
    overall_assessment: str
    strengths: list[str] = Field(default_factory=list)
    issues: list[JobDescriptionIssue] = Field(default_factory=list)
    missing_information: list[str] = Field(default_factory=list)
    skills_analysis: JobSkillsAnalysis
    improvement_recommendations: list[str] = Field(default_factory=list)
    improved_description: str | None = None
    disclaimer: str = Field(
        default=(
            "This analysis is an AI-assisted heuristic evaluation designed to help recruiters optimize job clarity and candidate conversion. "
            "It does not automatically modify the published job or guarantee hiring outcomes."
        ),
        description="Advisory disclaimer.",
    )


class JobDescriptionAnalysisResponse(BaseModel):
    job_id: UUID
    analysis: JobDescriptionAnalysisResult
